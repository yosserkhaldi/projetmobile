/** Langue d'un utilisateur, ou d'un code ; français par défaut. */
export const langOf = (userOrCode) => {
  const code = typeof userOrCode === 'string' ? userOrCode : userOrCode?.language;
  return languages.includes(code) ? code : 'FR';
};

